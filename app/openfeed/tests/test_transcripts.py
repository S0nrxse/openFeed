"""`GET /api/transcript/{id}/fetch` (transcripts.py): the contract an outside tool reads.

Network-free: httpx.AsyncClient is given a MockTransport that plays Invidious, and every
request it sees is recorded, so the tests can also check which host was contacted and
how many requests one fetch made.
"""

