BASE = "http://invidious.internal:3000"
VIDEO = "dQw4w9WgXcQ"
LISTING = {"transcripts": [
    {"label": "English", "languageCode": "en", "autoGenerated": False, "url": "https://evil.example/steal"},
    {"label": "English (auto-generated)", "languageCode": "en", "autoGenerated": True, "url": "/x"},
    {"label": "Deutsch", "languageCode": "de", "autoGenerated": True, "url": "/y"},
]}


def _transcript(language: str = "en", auto: bool = False, lines: int = 2) -> dict[str, Any]:
    return {"transcript": {"languageCode": language, "autoGenerated": auto, "body": [
        {"startMs": 1000 * i, "endMs": 1000 * i + 900, "line": f"line {i}", "type": "regular"} for i in range(lines)
    ]}}


class _Stream(httpx.AsyncByteStream):
    """A body that arrives as a stream, as from a real server. httpx pre-reads a Response
    built with content=, and the module reads raw chunks with a size cap."""

    def __init__(self, data: bytes) -> None:
        self.data = data

    async def __aiter__(self):
        yield self.data


def _response(status: int, data: bytes = b"", content_type: str = "", **headers: str) -> httpx.Response:
    if content_type:
        headers["content-type"] = content_type
    return httpx.Response(status, headers=headers, stream=_Stream(data))


def _json(payload: Any, status: int = 200) -> httpx.Response:
    return _response(status, json.dumps(payload).encode(), "application/json")


